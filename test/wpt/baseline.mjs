#!/usr/bin/env node
// Regenerate test/wpt/oracle-baseline.json from FULL oracle runs of the build named in test/vendor/wpt/VERSION.json (chromium.tag).
//   node test/wpt/baseline.mjs .scratch/results/wpt-A-run1-latest.json .scratch/results/wpt-A-run2-latest.json ... [--write]
// A subtest is in the baseline when it passes in every repetition of every run given (the intersection), so one flaky native pass is never a baseline pass.
// Refuses runs of another build, of another test selection than the whole vendored inventory, or fewer than two runs.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { PROJECT_ROOT } from '../harness/lib/util.mjs';
import { listTests } from './lib/inventory.mjs';

const OUT = resolve(PROJECT_ROOT, 'test/wpt/oracle-baseline.json');
const files = process.argv.slice(2).filter(a => !a.startsWith('--'));
const version = JSON.parse(readFileSync(resolve(PROJECT_ROOT, 'test/vendor/wpt/VERSION.json'), 'utf8'));
const build = `Chrome/${version.chromium.tag}`;
const ids = listTests().map(t => t.id).sort();

/** Subtest key as triage.mjs builds it: the name plus its occurrence number. @param {{name: string}[]} subtests */
function keys(subtests) {
  const seen = new Map();
  return subtests.map(s => { const n = seen.get(s.name) ?? 0; seen.set(s.name, n + 1); return n ? `${s.name} #${n + 1}` : s.name; });
}

const errors = [];
if (files.length < 2) errors.push('give at least two full oracle runs');
const docs = files.map(f => JSON.parse(readFileSync(resolve(f), 'utf8')));
for (const [i, d] of docs.entries()) {
  if (d.config.role !== 'oracle') errors.push(`${files[i]}: not an oracle run (${d.config.role})`);
  if (d.config.version !== build) errors.push(`${files[i]}: ${d.config.version}, the pinned WPT revision's oracle is ${build}`);
  const got = Object.keys(d.tests).sort();
  if (got.join('\n') !== ids.join('\n')) errors.push(`${files[i]}: ${got.length} tests, the vendored inventory has ${ids.length} (a partial run, or another revision)`);
  if (d.reps < 3) errors.push(`${files[i]}: ${d.reps} repetitions (3 needed)`);
}
if (errors.length) { for (const e of errors) console.error(e); process.exit(1); }

/** @type {Record<string, string[]>} */
const pass = {};
let total = 0; let unstable = 0;
for (const id of ids) {
  /** @type {Set<string>|null} */ let common = null;
  for (const d of docs) {
    const t = d.tests[id];
    if (!t.stable) unstable++;
    for (const run of t.runs) {
      const k = keys(run.subtests); const ok = new Set(k.filter((_, j) => run.subtests[j].status === 'PASS'));
      common = common === null ? ok : new Set([...common].filter(x => ok.has(x)));
    }
  }
  if (common?.size) { pass[id] = [...common]; total += common.size; }
}
const doc = {
  note: 'Per-subtest passes of the oracle build of the pinned WPT revision (test/vendor/wpt/VERSION.json chromium.tag), intersection of its full runs (every repetition passing in every run); generated by test/wpt/baseline.mjs. Used by test/wpt/triage.mjs only when the installed Canary is a different build (oracle drift: Canary auto-updates). Regenerate only from runs of the pinned build.',
  build, wptSha: version.sha, runs: docs.map(d => d.startedAt), pass,
};
console.log(`${build}: ${docs.length} runs, ${Object.keys(pass).length} files with a stable native pass, ${total} subtests; ${unstable} test results unstable within a run`);
if (process.argv.includes('--write')) { writeFileSync(OUT, JSON.stringify(doc, null, 1) + '\n'); console.log(`wrote ${OUT}`); }
