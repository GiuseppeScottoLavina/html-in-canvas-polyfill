#!/usr/bin/env node
// Builds the four framework apps of examples/frameworks/ into examples/frameworks/<fw>/dist/app.js (classic IIFE scripts, loaded
// AFTER dist/hic-live-polyfill.iife.js), and the React server-rendered page examples/frameworks/react/dist/hydrate.html.
//
//   (cd test/frameworks && npm install)      framework deps live HERE, never in the root package (zero runtime deps)
//   node test/frameworks/build.mjs           (run.mjs calls it first)
//
// esbuild comes from the ROOT devDependencies; framework packages resolve from test/frameworks/node_modules (nodePaths).
// Development builds on purpose: React, Vue and Svelte report more reconciliation / hydration problems in dev.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import * as esbuild from 'esbuild';
import { createRequire } from 'node:module';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '../..');
const EX = resolve(ROOT, 'examples/frameworks');
const NM = resolve(HERE, 'node_modules');

if (!existsSync(resolve(NM, 'react')) || !existsSync(resolve(NM, 'svelte'))) {
  console.error('test/frameworks/node_modules is missing: run `npm install` in test/frameworks first.');
  process.exit(2);
}
const req = (m) => import(pathToFileURL(resolve(NM, m)).href);

/** esbuild plugin: compile .svelte files with the svelte compiler from test/frameworks/node_modules. */
const sveltePlugin = {
  name: 'svelte',
  setup(build) {
    build.onLoad({ filter: /\.svelte$/ }, async (args) => {
      const { compile } = await req('svelte/src/compiler/index.js').catch(() => req('svelte/compiler/index.js'));
      const source = readFileSync(args.path, 'utf8');
      const out = compile(source, { filename: args.path, generate: 'client', dev: true, css: 'injected' });
      return { contents: out.js.code, loader: 'js', resolveDir: dirname(args.path), warnings: out.warnings.filter((w) => !String(w.code).startsWith('a11y')).map((w) => ({ text: w.message })) };
    });
  },
};

const common = {
  bundle: true, format: 'iife', platform: 'browser', target: 'chrome120', nodePaths: [NM], logLevel: 'warning', sourcemap: 'inline',
  jsx: 'automatic', conditions: ['development', 'browser'],
  define: { 'process.env.NODE_ENV': '"development"', __VUE_OPTIONS_API__: 'true', __VUE_PROD_DEVTOOLS__: 'false', __VUE_PROD_HYDRATION_MISMATCH_DETAILS__: 'true' },
};

export async function buildAll({ quiet = false } = {}) {
  const t0 = Date.now();
  const jobs = [
    { fw: 'react', entry: 'main.jsx' },
    { fw: 'vue', entry: 'main.js', alias: { vue: resolve(NM, 'vue/dist/vue.esm-bundler.js') } },
    { fw: 'svelte', entry: 'main.js', plugins: [sveltePlugin] },
    { fw: 'lit', entry: 'main.js' },
  ];
  for (const j of jobs) {
    await esbuild.build({ ...common, entryPoints: [resolve(EX, j.fw, j.entry)], outfile: resolve(EX, j.fw, 'dist/app.js'), alias: j.alias, plugins: j.plugins ?? [] });
  }
  // React server rendering: bundle App.jsx for node, render it to a string and write a page that hydrates it.
  const ssrOut = resolve(ROOT, '.scratch/frameworks-build/react-ssr.cjs');
  mkdirSync(dirname(ssrOut), { recursive: true });
  await esbuild.build({ ...common, platform: 'node', format: 'cjs', sourcemap: false, conditions: ['development'], outfile: ssrOut,
    stdin: { contents: `import { renderToString } from 'react-dom/server'; import { StrictMode } from 'react'; import { App } from './App.jsx';
      export const html = () => renderToString(<StrictMode><App /></StrictMode>);`, loader: 'jsx', resolveDir: resolve(EX, 'react') } });
  const { html } = createRequire(import.meta.url)(ssrOut);
  const page = readFileSync(resolve(EX, 'react/index.html'), 'utf8')
    .replace('../../../dist/hic-live-polyfill.iife.js', '../../../../dist/hic-live-polyfill.iife.js')
    .replace('<title>React 19 inside a drawable canvas</title>', '<title>React 19 hydrateRoot inside a drawable canvas</title>')
    .replace('<div id="root"></div>', `<div id="root">${html()}</div>`)
    .replace('<script src="dist/app.js"></script>', '<script>window.__ssrPanel = document.getElementById(\'panel\'); // test hook: the server-rendered node, to check hydration keeps it</script>\n<script src="app.js"></script>');
  writeFileSync(resolve(EX, 'react/dist/hydrate.html'), page.replace('<!doctype html>', '<!doctype html>\n<!-- GENERATED by test/frameworks/build.mjs (react-dom/server renderToString of App.jsx); do not edit -->'));
  // Probe: hydration of a drawable without id (see probes/react-hydrate-noid.jsx). Output under .scratch (not an example).
  const probeDir = resolve(ROOT, '.scratch/frameworks-build');
  await esbuild.build({ ...common, platform: 'node', format: 'cjs', sourcemap: false, conditions: ['development'], outfile: resolve(probeDir, 'probe-noid-ssr.cjs'), entryPoints: [resolve(HERE, 'probes/react-hydrate-noid.jsx')] });
  await esbuild.build({ ...common, outfile: resolve(probeDir, 'probe-noid.js'), globalName: 'Probe', entryPoints: [resolve(HERE, 'probes/react-hydrate-noid.jsx')] });
  const probeHtml = createRequire(import.meta.url)(resolve(probeDir, 'probe-noid-ssr.cjs')).ssr();
  writeFileSync(resolve(probeDir, 'probe-noid.html'), `<!doctype html><meta charset="utf-8"><title>probe</title><script src="/dist/hic-live-polyfill.iife.js"></script>
<div id="root">${probeHtml}</div><script src="probe-noid.js"></script><script>Probe.hydrate(document.getElementById('root')); setTimeout(() => { window.__probeDone = true; }, 300);</script>`);
  await buildDocSnippets();
  if (!quiet) console.log(`built react, vue, svelte, lit (+ react/dist/hydrate.html) in ${Date.now() - t0} ms`);
}

/** The section-5 code blocks of docs/guides/FRAMEWORKS.md, wrapped in the smallest page that mounts them, built under .scratch. */
export const SNIPPET_CSS = 'canvas{display:block;width:480px;height:320px;background:#fff} #form{box-sizing:border-box;width:480px;height:320px;padding:20px;margin:0;background:#e8eef8;font:16px/20px Arial,sans-serif} #form input{box-sizing:border-box;width:220px;height:30px;font:inherit}';
async function buildDocSnippets() {
  const md = readFileSync(resolve(ROOT, 'docs/guides/FRAMEWORKS.md'), 'utf8');
  const sec = md.slice(md.indexOf('## 5. Copy-paste patterns'), md.indexOf('## 6.'));
  const blocks = [...sec.matchAll(/```(\w+)\n([\s\S]*?)```/g)].map((m) => ({ lang: m[1], code: m[2] }));
  if (blocks.length !== 4) throw new Error(`FRAMEWORKS.md section 5: expected 4 code blocks, found ${blocks.length}`);
  const [react, vue, svelte, lit] = blocks;
  const dir = resolve(ROOT, '.scratch/frameworks-build/snippets');
  mkdirSync(dir, { recursive: true });
  const tpl = /\/\/ template: (.*)$/m.exec(vue.code)?.[1];
  if (!tpl) throw new Error('FRAMEWORKS.md Vue block: no "// template:" line');
  const sources = {
    'react.jsx': `import { useCallback, useRef, useState } from 'react';\nimport { createRoot } from 'react-dom/client';\n${react.code}\ncreateRoot(document.getElementById('root')).render(<Form />);\n`,
    'vue.js': `import { createApp, ref, watch } from 'vue';\ncreateApp({ setup() {\n${vue.code}\nreturn { canvas, form, name }; }, template: ${JSON.stringify(tpl)} }).mount('#root');\n`,
    'Snippet.svelte': svelte.code,
    'svelte.js': `import { mount } from 'svelte';\nimport Snippet from './Snippet.svelte';\nmount(Snippet, { target: document.getElementById('root') });\n`,
    'lit.js': `import { LitElement, html, unsafeCSS } from 'lit';\nimport { ref, createRef } from 'lit/directives/ref.js';\nclass SnippetEl extends LitElement {\nstatic properties = { name: { state: true } };\nstatic styles = unsafeCSS(${JSON.stringify(SNIPPET_CSS)});\n${lit.code}\n}\ncustomElements.define('snippet-el', SnippetEl);\n`,
  };
  for (const [f, src] of Object.entries(sources)) writeFileSync(resolve(dir, f), src);
  for (const [fw, entry, extra] of [['react', 'react.jsx', {}], ['vue', 'vue.js', { alias: { vue: resolve(NM, 'vue/dist/vue.esm-bundler.js') } }], ['svelte', 'svelte.js', { plugins: [sveltePlugin] }], ['lit', 'lit.js', {}]]) {
    await esbuild.build({ ...common, entryPoints: [resolve(dir, entry)], outfile: resolve(dir, `${fw}.bundle.js`), ...extra });
    writeFileSync(resolve(dir, `${fw}.html`), `<!doctype html><meta charset="utf-8"><title>FRAMEWORKS.md ${fw} snippet</title><style>body{margin:16px} ${SNIPPET_CSS}</style>
<script src="/dist/hic-live-polyfill.iife.js"></script>
${fw === 'lit' ? '<snippet-el id="root"></snippet-el>' : '<div id="root"></div>'}
<script src="/__snip/${fw}.bundle.js"></script>`);
  }
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) await buildAll();
