// Regenerates, from src/contracts/features.js (single source of truth), the generated block of docs/SUPPORT-MATRIX.md and the runtime status
// lookup src/contracts/feature-status.js. `renderMatrix(doc)` returns the document with the block regenerated and `renderStatusModule()` the
// whole status module; scripts/check-repo.mjs (G-doc-sync) compares both with the files.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const { FEATURES } = await import(pathToFileURL(join(root, 'src/contracts/features.js')).href);
const BEGIN = '<!-- BEGIN GENERATED FEATURES -->';
const END = '<!-- END GENERATED FEATURES -->';
const groups = [['supported', 'Supported'], ['limited', 'Limited (works, with documented deviations)'], ['deviation', 'Deviations from the standard behaviour'], ['unsupported', 'Unsupported (refused loudly)']];
const esc = (/** @type {string} */ s) => s.replace(/\|/g, '\\|');
export const MATRIX_PATH = join(root, 'docs/SUPPORT-MATRIX.md');
export const STATUS_PATH = join(root, 'src/contracts/feature-status.js');

/** @param {string} doc  the current SUPPORT-MATRIX.md @returns {string} */
export function renderMatrix(doc) {
  let out = '';
  for (const [status, title] of groups) {
    const rows = FEATURES.filter((/** @type {any} */ f) => f.status === status);
    out += `### ${title}\n\n| id | what | reason / the one thing to know |\n|---|---|---|\n`;
    for (const f of rows) out += `| \`${f.id}\` | ${esc(f.summary)} | ${esc(f.reason)} |\n`;
    out += '\n';
  }
  const i = doc.indexOf(BEGIN), j = doc.indexOf(END);
  if (i < 0 || j < 0) throw new Error('markers missing in SUPPORT-MATRIX.md');
  return doc.slice(0, i + BEGIN.length) + '\n\n' + out + doc.slice(j);
}

/** @returns {string} the content of src/contracts/feature-status.js: every id of FEATURES with its status, grouped by status */
export function renderStatusModule() {
  const bad = FEATURES.filter((/** @type {any} */ f) => !groups.some(([s]) => s === f.status) || !/^[a-z0-9-]+$/.test(f.id));
  if (bad.length) throw new Error(`features.js: unknown status or an id that is not kebab-case: ${bad.map((/** @type {any} */ f) => f.id).join(', ')}`);
  const lines = groups.map(([status]) => `  ${status}: [${FEATURES.filter((/** @type {any} */ f) => f.status === status).map((/** @type {any} */ f) => `'${f.id}'`).join(', ')}],`);
  return `// GENERATED by scripts/gen-support-matrix.mjs (npm run docs:sync) from src/contracts/features.js. Do not edit: G-doc-sync
// (scripts/check-repo.mjs) fails when this file differs from what the generator renders.
/**
 * The runtime's feature status lookup (id -> status). The runtime reads only the status of a feature: importing this module instead of
 * features.js lets a bundler drop the public FEATURES table (every summary and reason) from an app that imports neither FEATURES nor
 * featureById. The classic core build (scripts/build.mjs, lean-features) answers featureStatus from its lean FEATURES instead, so it
 * holds each id and status once.
 */

/** @typedef {'supported'|'limited'|'unsupported'|'deviation'} FeatureStatus */

const BY_STATUS = {
${lines.join('\n')}
};

/** every feature id of src/contracts/features.js -> its status */
export const FEATURE_STATUS = /** @type {Readonly<Record<string, FeatureStatus>>} */ (Object.freeze(Object.fromEntries(Object.entries(BY_STATUS).flatMap(([status, ids]) => ids.map((id) => [id, status])))));

/** @type {(id: string) => FeatureStatus|undefined} the status of a feature id; undefined for an id that is not in the table */
export const featureStatus = (id) => (Object.hasOwn(FEATURE_STATUS, id) ? FEATURE_STATUS[id] : undefined);
`;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeFileSync(MATRIX_PATH, renderMatrix(readFileSync(MATRIX_PATH, 'utf8')));
  writeFileSync(STATUS_PATH, renderStatusModule());
  console.log('SUPPORT-MATRIX.md and src/contracts/feature-status.js regenerated:', FEATURES.length, 'features');
}
